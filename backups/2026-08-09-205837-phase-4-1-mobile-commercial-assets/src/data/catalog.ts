export function getProductBySlug(slug: string) {
  return products.find((product) => product.slug === slug);
}

export function getProductById(id: string) {
  return products.find((product) => product.id === id);
}

export function getBundleBySlug(slug: string) {
  return bundles.find((bundle) => bundle.slug === slug);
}

export function getBundleById(id: string) {
  return bundles.find((bundle) => bundle.id === id);
}

export function getBundleProducts(bundle: Bundle) {
  return bundle.productIds.map(getProductById).filter(Boolean) as Product[];
}

export function getCategoryBySlug(slug: string) {
  return categories.find((category) => category.slug === slug);
}

export function getBrandBySlug(slug: string) {
  return brands.find((brand) => brand.slug === slug);
}

export function getProductsByCategory(slug: string) {
  return products.filter((product) => product.categorySlug === slug);
}

export function getProductsByBrand(slug: string) {
  return products.filter((product) => product.brandSlug === slug);
}

export function getProductsByIds(ids: string[], limit = ids.length) {
  return ids.map(getProductById).filter(Boolean).slice(0, limit) as Product[];
}

export function getRelatedProducts(product: Product, limit = 4) {
  const explicit = getProductsByIds(product.relatedProductIds ?? []);
  const compatible = getProductsByIds(product.compatibleWith);
  const sameCategory = products.filter(
    (item) => item.categorySlug === product.categorySlug && item.id !== product.id,
  );

  return [...explicit, ...compatible, ...sameCategory]
    .filter((item, index, array) => array.findIndex((candidate) => candidate.id === item.id) === index)
    .slice(0, limit);
}

export function getUpsellProducts(product: Product, limit = 4) {
  return getProductsByIds(product.upsellProductIds ?? [], limit);
}

export function getCompatibleProducts(product: Product, limit = 4) {
  return getProductsByIds(product.compatibleWith, limit);
}

export function searchProducts(query: string) {
  const cleanQuery = query.trim().toLowerCase();

  if (!cleanQuery) {
    return products;
  }

  return products.filter((product) =>
    [
      product.name,
      product.shortName,
      product.shortDescription,
      product.brand,
      product.brandSlug,
      product.category,
      product.categorySlug,
      product.subcategory,
      product.subcategorySlug,
      product.sku,
      ...(product.ageGroup ?? []),
      ...(product.tags ?? []),
      ...product.variants.flatMap((variant) => [variant.sku, variant.name, ...Object.values(variant.attributes)]),
    ]
      .filter(Boolean)
      .join(" ")
      .toLowerCase()
      .includes(cleanQuery),
  );
}

export function makeCatalogCsv() {
  const header = "sku,name,brand,category,retailPrice,cost,stockQuantity,stockStatus";
  const rows = products.map((product) =>
    [
      product.sku,
      product.name,
      product.brand,
      product.category,
      product.retailPrice,
      product.cost ?? "",
      product.stockQuantity ?? "",
      product.stockStatus,
    ]
      .map((value) => `"${String(value).replaceAll('"', '""')}"`)
      .join(","),
  );

  return [header, ...rows].join("\n");
}

export function catalogSummary() {
  const variantCount = products.reduce((total, product) => total + product.variants.length, 0);
  return {
    products: products.length,
    categories: categories.length,
    brands: brands.length,
    variants: variantCount,
    bundles: bundles.length,
  };
}
